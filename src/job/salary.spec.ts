describe('parseAmount', () => {
  it.each([
    ['1500', 1500],
    ['1,500', 1500],
    ['1.500', 1500],
    ['1 500', 1500],
    ['2, 500', 2500],
    ['9.00', 9],
    ['10.63', 10.63],
    ['1,500.50', 1500.5],
  ])('%s → %d', (raw, value) => {
    expect(parseAmount(raw)).toBe(value);
  });
});
